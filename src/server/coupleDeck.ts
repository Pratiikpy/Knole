export const COUPLE_DECK: CoupleQuestion[] = [
  ...playful,
  ...deep,
  ...gratitude,
  ...repair,
  ...future,
  ...intimacy,
];

const BY_ID = new Map(COUPLE_DECK.map((c) => [c.id, c]));
export const coupleQuestionById = (id: string): CoupleQuestion | null => BY_ID.get(id) ?? null;

/** Deterministic per-couple daily pick: same question for both partners all day, different per couple. */
export function coupleQuestionFor(coupleId: string, dateKey: string): CoupleQuestion {
  const s = `${coupleId}:${dateKey}`;
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return COUPLE_DECK[Math.abs(h) % COUPLE_DECK.length];
}
