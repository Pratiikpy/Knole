// couple per day (hash of coupleId + date). Voice rules: askable out loud over dinner, no
// therapy-speak, no quiz-show cuteness; conflict-repair questions assume goodwill; intimacy
// questions are warm, never explicit. A couple takes ~7 months to see a repeat.

